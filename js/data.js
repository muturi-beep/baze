// ---- lookups ----
export var artistById = {};
export var producerById = {};
export var albumById = {};
export var trackById = {};

ARTISTS.forEach(function (a) {
  artistById[a.id] = a;
});
PRODUCERS.forEach(function (p) {
  producerById[p.id] = p;
});
ALBUMS.forEach(function (al) {
  albumById[al.id] = al;
});

TRACKS.forEach(function (t) {
  trackById[t.id] = Object.assign({}, t, {
    artist: artistById[t.artistId],
    album: albumById[t.albumId],
    producers: (t.producerIds || [])
      .map(function (pid) {
        return producerById[pid];
      })
      .filter(Boolean),
  });
});
